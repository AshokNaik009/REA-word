import { expect, test } from '@playwright/test'
import { readFile } from 'node:fs/promises'

test.beforeEach(async ({ page }) => {
  await page.goto('/')
  await expect(page.getByRole('textbox', { name: 'Document editor' })).toBeVisible()
  await page.getByRole('button', { name: 'New document', exact: true }).click()
  await expect(page.getByRole('textbox', { name: 'Document title' })).toHaveValue('Untitled document')
  await expect.poll(() => page.evaluate(() => Boolean(window.wordcraft))).toBe(true)
})

test('UI formatting, shortcuts and automation share the editor and save path', async ({ page }) => {
  const editor = page.getByRole('textbox', { name: 'Document editor' })
  await editor.fill('Alpha beta')
  expect(await page.evaluate(() => window.wordcraft!.execute('select.text', { text: 'beta' }))).toMatchObject({ ok: true })
  await page.getByRole('button', { name: 'Superscript', exact: true }).click()
  await expect(editor.locator('sup')).toHaveText('beta')
  expect(await page.evaluate(() => window.wordcraft!.execute('format.subscript'))).toMatchObject({ ok: true })
  await expect(editor.locator('sub')).toHaveText('beta')
  await expect(editor.locator('sup')).toHaveCount(0)
  await editor.press('Meta+b')
  await expect(editor.locator('strong')).toHaveText('beta')
  await editor.press('Meta+b')
  await expect(editor.locator('strong')).toHaveCount(0)
  await expect(page.locator('.save-indicator.saved')).toBeVisible()
  await page.reload()
  await expect(editor.locator('sub')).toHaveText('beta')
  const result = await page.evaluate(() => window.wordcraft!.request({ method: 'engine.execute', params: { command: 'mailings.merge' } }))
  expect(result).toMatchObject({ ok: false, error: { code: 'UNKNOWN_COMMAND' } })
})

test('paragraph settings survive autosave and reload, and undo as one edit', async ({ page }) => {
  const editor = page.getByRole('textbox', { name: 'Document editor' })
  await editor.fill('Paragraph settings test')
  await editor.press('Meta+a')
  await page.getByRole('button', { name: 'Paragraph settings', exact: true }).click()
  await page.getByRole('spinbutton', { name: 'Space before', exact: true }).fill('12')
  await page.getByRole('spinbutton', { name: 'Left indent', exact: true }).fill('36')
  await page.getByRole('spinbutton', { name: 'First line indent', exact: true }).fill('-18')
  await page.getByLabel('Paragraph direction', { exact: true }).selectOption('rtl')
  await page.getByRole('checkbox', { name: 'Keep with next', exact: true }).check()
  await page.getByRole('button', { name: 'Apply paragraph settings', exact: true }).click()
  await expect(editor.locator('p')).toHaveAttribute('dir', 'rtl')
  await expect(editor.locator('p')).toHaveAttribute('data-wc-space-before', '12')
  await page.getByRole('button', { name: 'Undo (Cmd/Ctrl+Z)', exact: true }).click()
  await expect(editor.locator('p')).not.toHaveAttribute('dir', 'rtl')
  await page.getByRole('button', { name: 'Redo (Cmd/Ctrl+Shift+Z)', exact: true }).click()
  await expect(page.locator('.save-indicator.saved')).toBeVisible()
  await page.reload()
  await expect(editor.locator('p')).toHaveAttribute('dir', 'rtl')
  await expect(editor.locator('p')).toHaveAttribute('data-wc-indent-left', '36')
})

test('page-break shortcut and DOCX import preserve supported document features', async ({ page }) => {
  const editor = page.getByRole('textbox', { name: 'Document editor' })
  await editor.fill('Before the break')
  await editor.press('Meta+End')
  await editor.press('Meta+Enter')
  await page.keyboard.insertText('After the break')
  await expect(editor.locator('[data-wordcraft-page-break]')).toHaveCount(1)
  await page.evaluate(() => window.wordcraft!.execute('select.text', { text: 'Before' }))
  await page.getByRole('button', { name: 'Superscript', exact: true }).click()
  await page.getByRole('button', { name: 'Export', exact: true }).click()
  await page.locator('input[name="format"][value="docx"]').check()
  const downloaded = page.waitForEvent('download')
  await page.getByRole('button', { name: 'Export .docx', exact: true }).click()
  const bytes = await readFile((await (await downloaded).path())!)
  await page.getByLabel('Open document file', { exact: true }).setInputFiles({ name: 'features.docx', mimeType: 'application/vnd.openxmlformats-officedocument.wordprocessingml.document', buffer: bytes })
  await expect(page.getByRole('status')).toContainText('DOCX imported as an editable copy')
  await expect(editor.locator('[data-wordcraft-page-break]')).toHaveCount(1)
  await expect(editor.locator('sup')).toHaveText('Before')
  await expect(editor).toContainText('After the break')
  await expect(page.locator('.save-indicator.saved')).toBeVisible()
  await page.reload()
  await expect(editor.locator('[data-wordcraft-page-break]')).toHaveCount(1)
})

test('command palette searches the engine registry rather than a separate feature list', async ({ page }) => {
  const editor = page.getByRole('textbox', { name: 'Document editor' })
  await editor.fill('Palette formatting')
  await editor.press('Meta+a')
  await page.getByRole('button', { name: /Find a command/ }).click()
  await page.getByRole('textbox', { name: 'Search commands' }).fill('format.superscript')
  await page.getByRole('dialog').getByRole('button', { name: /Superscript/ }).click()
  await expect(editor.locator('sup')).toHaveText('Palette formatting')
})

import { execFileSync } from 'node:child_process'
import { readFileSync, writeFileSync, readdirSync } from 'node:fs'
import { dirname, resolve, relative } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const snapshotPath = resolve(root, 'docs/upstream-inventory.json')
const upstreamIndex = process.argv.indexOf('--upstream')

function walk(path) {
  return readdirSync(path, { withFileTypes: true }).flatMap(entry => {
    const next = resolve(path, entry.name)
    return entry.isDirectory() ? walk(next) : [next]
  })
}

if (upstreamIndex !== -1) {
  const upstream = resolve(process.argv[upstreamIndex + 1] ?? '')
  const catalogFile = 'crates/engine/src/catalog.rs'
  const catalogText = readFileSync(resolve(upstream, catalogFile), 'utf8')
  const catalog = catalogText.split('\n').flatMap((line, index) => {
    const match = /^([^|"]+)\|([^|]+)\|([^|]+)\|([\w.]+)$/.exec(line)
    return match ? [{ tab: match[1], group: match[2], label: match[3], id: match[4], source: `${catalogFile}:${index + 1}` }] : []
  })
  const commands = new Map()
  for (const file of walk(resolve(upstream, 'crates/engine/src')).filter(file => file.endsWith('.rs'))) {
    const text = readFileSync(file, 'utf8')
    for (const match of text.matchAll(/CommandSpec::new\(\s*"([^"]+)"\s*,\s*"([^"]*)"/g)) {
      const line = text.slice(0, match.index).split('\n').length
      commands.set(match[1], { id: match[1], label: match[2], source: `${relative(upstream, file)}:${line}` })
    }
  }
  const inventory = {
    repository: 'https://github.com/storytold/wordcraft',
    revision: execFileSync('git', ['rev-parse', 'HEAD'], { cwd: upstream, encoding: 'utf8' }).trim(),
    method: 'Catalog rows and literal CommandSpec::new IDs. Dynamic registrations and UI-only commands are not an exhaustive engine inventory.',
    catalog,
    commands: [...commands.values()].sort((a, b) => a.id.localeCompare(b.id)),
    modelModules: walk(resolve(upstream, 'crates/doc/src')).filter(file => file.endsWith('.rs') && !file.includes('/tests')).map(file => relative(upstream, file)).sort(),
  }
  writeFileSync(snapshotPath, `${JSON.stringify(inventory, null, 2)}\n`)
}

const inventory = JSON.parse(readFileSync(snapshotPath, 'utf8'))
const source = readFileSync(resolve(root, 'src/engine/commands.ts'), 'utf8')
const available = new Set([...source.matchAll(/define\('([^']+)'/g)].map(match => match[1]))
const catalogIds = new Set(inventory.catalog.map(item => item.id))
const allIds = new Set([...catalogIds, ...inventory.commands.map(item => item.id)])
const rows = [...allIds].sort().map(id => {
  const entries = inventory.catalog.filter(item => item.id === id)
  const spec = inventory.commands.find(item => item.id === id)
  const title = entries[0]?.label ?? spec?.label ?? id
  const location = entries[0] ? `${entries[0].tab} / ${entries[0].group}` : 'Engine'
  const status = available.has(id) ? 'Partial: callable TS command' : 'Not ported to TS engine'
  return `| \`${id}\` | ${title.replaceAll('|', '/')} | ${location} | ${status} | \`${entries[0]?.source ?? spec?.source}\` |`
})
const present = [...allIds].filter(id => available.has(id)).length
const report = `# Upstream Feature Inventory

Generated by \`npm run parity\`. Upstream revision: \`${inventory.revision}\`.

- ${inventory.catalog.length} catalog entries; ${catalogIds.size} distinct catalog command IDs.
- ${inventory.commands.length} literal engine command IDs; ${allIds.size} IDs in their union.
- ${present} IDs have callable TypeScript implementations; ${allIds.size - present} have no TS engine implementation.
- Callable does not mean feature parity. Every migrated command remains **partial** until its upstream parameters, document semantics, file exchange, and platform behavior are verified.
- Some existing UI features are not yet migrated to the command layer; they are intentionally not counted as callable commands.

## Evidence And Limits

Source: ${inventory.repository}/tree/${inventory.revision}. Paths below refer to that revision.
${inventory.method}
The catalog includes upstream aspirations as well as working features. This is a migration work list, not a claim that every upstream feature works or a Microsoft Word parity percentage.
The checked-in JSON also inventories document-model modules. Refresh explicitly with \`node scripts/parity.mjs --upstream /path/to/wordcraft-original\`; ordinary reporting needs no Rust or upstream checkout.

## Command Matrix

| ID | Feature | Location | TS Status | Upstream Evidence |
|---|---|---|---|---|
${rows.join('\n')}
`
const reportPath = resolve(root, 'docs/feature-parity.md')
if (process.argv.includes('--check')) {
  if (readFileSync(reportPath, 'utf8') !== report) throw new Error('Parity report is stale. Run npm run parity.')
} else {
  writeFileSync(reportPath, report)
}
console.log(`${present}/${allIds.size} upstream IDs callable (partial); ${allIds.size - present} not ported. No full-parity claim.`)
